#!/usr/bin/env python3
"""Export a lookup table for the vehicle-feature SUMO road-time model.

Vehicle attributes are not numerically swept. The table uses only complete,
distinct vehicle profiles that actually occur in the supplied training CSVs.
This avoids inventing impossible combinations such as a truck length paired
with a passenger-car acceleration.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd


REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import model_catching_sumo_v1 as base  # noqa: E402


BASE_FEATURES = ["has_waiting", "road_length", "turn_type", "road_flow", "lane_flow"]
VEHICLE_FEATURES = [
    "vehicle_length",
    "vehicle_min_gap",
    "vehicle_max_speed",
    "vehicle_accel",
    "vehicle_decel",
    "vehicle_sigma",
]
FEATURE_COLS = BASE_FEATURES + VEHICLE_FEATURES
SOURCE_LABEL = "travel_time_label"
LABEL_COL = "travel_time_no_waiting"


def _load_one_frame(csv_path: str) -> pd.DataFrame:
    columns = list(pd.read_csv(csv_path, nrows=0).columns)
    required = FEATURE_COLS + [SOURCE_LABEL]
    missing = [column for column in required if column not in columns]
    if missing:
        raise ValueError(
            f"{csv_path}: missing vehicle-feature columns: {missing}. "
            "Use CSVs generated by traci_vehicle_features.py."
        )
    df = pd.read_csv(csv_path, usecols=required).dropna(subset=required).copy()
    df["has_waiting"] = df["has_waiting"].astype(int)
    df["turn_type"] = df["turn_type"].astype(int)
    for column in [c for c in FEATURE_COLS if c not in {"has_waiting", "turn_type"}]:
        df[column] = df[column].astype(float)
    df[LABEL_COL] = df[SOURCE_LABEL].astype(float)

    finite_columns = [c for c in FEATURE_COLS if c != "has_waiting"] + [LABEL_COL]
    valid = (
        np.isfinite(df[finite_columns]).all(axis=1)
        & (df[LABEL_COL] > 0)
        & (df["road_length"] > 0)
        & (df["road_flow"] >= 0)
        & (df["lane_flow"] >= 0)
        & (df["vehicle_length"] > 0)
        & (df["vehicle_min_gap"] >= 0)
        & (df["vehicle_max_speed"] > 0)
        & (df["vehicle_accel"] > 0)
        & (df["vehicle_decel"] > 0)
        & (df["vehicle_sigma"] >= 0)
        & (df["vehicle_sigma"] <= 1)
    )
    dropped = int((~valid).sum())
    if dropped:
        print(f"[INFO] {csv_path}: dropped invalid rows={dropped}")
    df = df.loc[valid, FEATURE_COLS + [LABEL_COL]].reset_index(drop=True)
    if df.empty:
        raise ValueError(f"{csv_path}: no valid vehicle-feature rows remain")
    print(f"[INFO] {csv_path}: valid rows={len(df)}")
    return df


def load_training_frame(csv_paths, q99_filter=False, q99_quantile=0.99):
    df = pd.concat(
        [_load_one_frame(path) for path in csv_paths],
        ignore_index=True,
        copy=False,
    )
    if q99_filter:
        threshold = float(df[LABEL_COL].quantile(q99_quantile))
        before = len(df)
        df = df[df[LABEL_COL] <= threshold].reset_index(drop=True)
        print(f"[INFO] P99 domain filter threshold={threshold}; removed={before - len(df)}")
    else:
        print("[INFO] P99 domain filter: DISABLED")
    if df.empty:
        raise ValueError("No rows remain for catching")
    return df


def iter_cases(
    road_lengths,
    turn_types,
    road_flow_values,
    lane_flow_values,
    vehicle_profiles,
):
    for road_length in road_lengths:
        for turn_type in turn_types:
            for has_waiting in (False, True):
                for road_flow in road_flow_values:
                    for lane_flow in lane_flow_values:
                        if float(lane_flow) > float(road_flow):
                            continue
                        for profile in vehicle_profiles:
                            row = {
                                "has_waiting": bool(has_waiting),
                                "road_length": float(road_length),
                                "turn_type": int(turn_type),
                                "road_flow": float(road_flow),
                                "lane_flow": float(lane_flow),
                            }
                            row.update(
                                {
                                    column: float(value)
                                    for column, value in zip(VEHICLE_FEATURES, profile)
                                }
                            )
                            yield row


def _predictor_features(predictor):
    try:
        features = list(predictor.feature_metadata.get_features())
        if features:
            return features
    except Exception:
        pass
    return FEATURE_COLS.copy()


def _validate_predictor_features(features) -> None:
    missing = [column for column in features if column not in FEATURE_COLS]
    extra = [column for column in FEATURE_COLS if column not in features]
    if missing or extra:
        raise ValueError(
            "Model/catch feature mismatch: "
            f"model-only={missing}, catch-only={extra}, expected={FEATURE_COLS}"
        )


def build_cache_table(args) -> None:
    df = load_training_frame(
        args.csv_files,
        q99_filter=args.q99_filter,
        q99_quantile=args.q99_quantile,
    )
    for path in [args.output_txt, args.unique_csv, args.turn_mapping_json]:
        base.ensure_parent_dir(path)
    if args.output_csv:
        base.ensure_parent_dir(args.output_csv)

    unique_df = (
        df[FEATURE_COLS]
        .drop_duplicates()
        .sort_values(FEATURE_COLS)
        .reset_index(drop=True)
    )
    unique_df.to_csv(args.unique_csv, index=False)
    base.save_turn_mapping(
        {"unknown": 0, "left": 1, "straight": 2, "right": 3, "uturn": 4},
        args.turn_mapping_json,
    )

    road_lengths = sorted(float(value) for value in df["road_length"].unique())
    turn_types = sorted(int(value) for value in df["turn_type"].unique())
    profile_df = (
        df[VEHICLE_FEATURES]
        .drop_duplicates()
        .sort_values(VEHICLE_FEATURES)
        .reset_index(drop=True)
    )
    vehicle_profiles = list(profile_df.itertuples(index=False, name=None))

    max_road_flow = (
        int(math.ceil(float(df["road_flow"].max())))
        if args.max_road_flow is None
        else args.max_road_flow
    )
    road_flow_values = list(range(0, max_road_flow + 1, args.road_flow_step))
    max_lane_flow = (
        float(max_road_flow)
        if args.max_lane_flow is None
        else float(args.max_lane_flow)
    )
    lane_flow_values = base.float_range(
        0.0,
        max_lane_flow,
        args.lane_flow_step,
        args.precision,
    )

    print("[INFO] table dimensions:")
    print(f"       road_length observed values = {len(road_lengths)}")
    print(f"       turn_type observed values   = {turn_types}")
    print(f"       vehicle profiles observed   = {len(vehicle_profiles)}")
    for index, profile in enumerate(vehicle_profiles, start=1):
        print(f"       vehicle profile [{index}]   = {dict(zip(VEHICLE_FEATURES, profile))}")
    print(f"       road_flow values            = 0..{max_road_flow}")
    print(f"       lane_flow values            = 0..min({max_lane_flow}, road_flow)")

    try:
        from autogluon.tabular import TabularPredictor
    except ImportError as exc:
        raise RuntimeError("AutoGluon is required for catching") from exc

    predictor = TabularPredictor.load(args.model_path)
    predictor_features = _predictor_features(predictor)
    _validate_predictor_features(predictor_features)

    output_columns = FEATURE_COLS + [LABEL_COL]
    txt_path = Path(args.output_txt)
    csv_path = Path(args.output_csv) if args.output_csv else None
    base.write_txt_header(txt_path, output_columns)
    if csv_path is not None and csv_path.exists():
        csv_path.unlink()

    cases = iter_cases(
        road_lengths,
        turn_types,
        road_flow_values,
        lane_flow_values,
        vehicle_profiles,
    )
    total = 0
    for batch_number, batch in enumerate(base.batch_iter(cases, args.chunk_size), start=1):
        cases_df = pd.DataFrame(batch, columns=FEATURE_COLS)
        cases_df["has_waiting"] = cases_df["has_waiting"].astype("category")
        cases_df["turn_type"] = cases_df["turn_type"].astype(int)
        predictions = pd.Series(
            predictor.predict(cases_df[predictor_features])
        ).astype(float)
        if args.clip_min is not None:
            predictions = predictions.clip(lower=float(args.clip_min))
        output = cases_df[FEATURE_COLS].copy()
        output[LABEL_COL] = predictions.to_numpy()
        base.append_txt_rows(txt_path, output, output_columns)
        if csv_path is not None:
            base.append_csv_rows(csv_path, output, header=(batch_number == 1))
        total += len(output)
        print(f"[INFO] batch {batch_number}: wrote={len(output)}, total={total}")

    print(f"[DONE] lookup table rows: {total}")
    print(f"[DONE] txt output -> {txt_path}")


def build_argparser():
    parser = base.build_argparser()
    parser.description = "Build a lookup table for the SUMO vehicle-feature model."
    parser.set_defaults(
        model_path="models_vehicle_features_v1",
        output_txt="model_catching_sumo_vehicle_features_v1.txt",
        unique_csv="unique_feature_combinations_vehicle_features_v1.csv",
        turn_mapping_json="turn_mapping_vehicle_features_v1.json",
    )
    return parser


def main() -> None:
    args = build_argparser().parse_args()
    if args.expected_csv_count < 0:
        raise ValueError("--expected-csv-count must be >= 0")
    if not 0.0 < args.q99_quantile < 1.0:
        raise ValueError("--q99-quantile must be between 0 and 1")
    if args.max_road_flow is not None and args.max_road_flow < 0:
        args.max_road_flow = None
    if args.clip_min is not None and math.isnan(float(args.clip_min)):
        args.clip_min = None
    args.csv_files = base.resolve_csv_inputs(
        args.csv,
        args.csv_glob,
        args.csv_list,
        args.expected_csv_count,
    )
    print("[Vehicle Features] " + ",".join(VEHICLE_FEATURES))
    build_cache_table(args)


if __name__ == "__main__":
    main()
